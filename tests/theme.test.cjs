const {readFileSync}=require('node:fs'),{runInNewContext}=require('node:vm'),assert=require('node:assert/strict');
const t=runInNewContext(readFileSync('dist/themes.js','utf8')+'\nPalaisTheme;',{});
const mem=new Map(),store={getItem:k=>mem.get(k)??null,setItem:(k,v)=>mem.set(k,v)};
assert.equal(t.current(store),'macaron');
assert.ok(t.save('classic',store));assert.equal(t.current(store),'classic');
assert.equal(t.save('missing',store),false);assert.equal(t.current(store),'classic');
mem.set('palais.theme','gold-rose');assert.equal(t.current(store),'macaron');
assert.equal(t.current({getItem(){throw Error('blocked')}}),'macaron');
assert.equal(t.save('classic',{setItem(){throw Error('quota')}}),false);
assert.equal(t.apply('unknown'),'macaron');
assert.equal(new Set(t.list.map(x=>x.id)).size,t.list.length);
assert.equal(t.mascot(store),'cat');assert.ok(t.setMascot('dog',null,store));assert.equal(t.mascot(store),'dog');
assert.equal(t.setMascot('dragon',null,store),false);assert.equal(t.nextMascot('dog'),'cat');
const css=readFileSync('dist/themes.css','utf8');
for(const x of t.list.filter(x=>x.id!=='classic'))assert.ok(css.includes(`:root[data-theme="${x.id}"]`),x.id+' 缺少样式');
for(const x of t.list.filter(x=>x.token))for(const k of ['--t-page','--t-text','--t-accent','--t-card','--t-line'])assert.ok(new RegExp(`:root\\[data-theme="${x.id}"\\]\\{[^}]*${k}:`).test(css),x.id+' 缺少令牌 '+k);
const pets=runInNewContext(readFileSync('dist/pets-art.js','utf8')+'\nPalaisPets;',{});
for(const m of t.mascots)assert.match(pets[m.id],/^data:image\/svg\+xml,/);
for(const k of ['cat','bunny','dog'])assert.ok(pets[k],'家园宠物缺少 '+k);
console.log('theme tests passed');
