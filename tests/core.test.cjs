const {readFileSync}=require('node:fs');
const {runInNewContext}=require('node:vm');
const assert=require('node:assert/strict');
const core=runInNewContext(readFileSync('dist/core.js','utf8')+'\nPalaisCore;', {URL});
assert.equal(core.apiURL('https://example.com/v1/','models'),'https://example.com/v1/models');
assert.equal(core.apiURL('https://example.com/v1/chat/completions','models'),'https://example.com/v1/models');
assert.equal(core.apiURL('https://example.com/api/models','chat/completions'),'https://example.com/api/chat/completions');
assert.throws(()=>core.apiURL('http://example.com/v1','models'));
assert.throws(()=>core.apiURL('https://example.com/v1?key=secret','models'));
assert.equal(JSON.stringify(core.modelIds({data:[{id:'z'},{id:'a'},{id:'a'},{}]})), '["a","z"]');
assert.throws(()=>core.modelIds({data:[]}));
assert.throws(()=>core.modelIds({models:[]}));
const entries=[{id:'always',name:'背景',content:'常驻设定',enabled:true,roleId:'',mode:'always',keys:''},{id:'rose',name:'王都',content:'王都是粉金色',enabled:true,roleId:'rose',mode:'keywords',keys:'王都， Palace'},{id:'off',name:'关闭',content:'不出现',enabled:false,mode:'always',keys:''},{id:'other',name:'其他角色',content:'不出现',enabled:true,roleId:'lune',mode:'always',keys:''}];
assert.equal(JSON.stringify(core.activeEntries(entries,'rose',[{content:'王都是什么样的？'}]).map(e=>e.id)),'["always","rose"]');
assert.equal(JSON.stringify(core.activeEntries(entries,'rose',[{content:'PALACE'}]).map(e=>e.id)),'["always","rose"]');
assert.equal(JSON.stringify(core.activeEntries(entries,'rose',[{content:'你好'}]).map(e=>e.id)),'["always"]');
assert.equal(JSON.stringify(core.activeEntries(entries,'rose',[{content:'王都'},...Array.from({length:6},()=>({content:'你好'}))]).map(e=>e.id)),'["always"]');
assert.equal(core.systemPrompt({id:'rose',prompt:'你是角色'},[],[]),'你是角色');
assert.match(core.systemPrompt({id:'rose',prompt:'你是角色'},entries,[{content:'王都'}]),/王都是粉金色/);
console.log('15 checks passed: model endpoints, model parsing, worldbook trigger, scope and prompt injection.');
